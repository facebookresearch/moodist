// Moodist Api versioning - generated values for version checking

#pragma once

#include <cstdint>

namespace moodist {

// Api version - increment when struct layout changes
// 3: RDMA direct-read functions appended to CoreApi (rdmaRegister, rdmaRead, rdmaWorkDestroy, rdmaWorkWait)
// 4: communication pool functions appended to CoreApi (processGroupCommPoolAllocate, commPoolOffset)
// 5: createProcessGroup takes the process group's timeout
// 6: the PREMUL_SUM factors of processGroupReduceScatter and processGroupAllreduce are doubles, and
//    processGroupReduce takes one
// 7: CUDA allocator statistics, memory limit and private pools appended to CoreApi (cudaAllocatorGetStats ...
//    cudaAllocatorGetPoolUseCount); the allocation functions throw CudaOutOfMemoryError when out of memory
//
// Besides the _C.so <-> libmoodist.so handshake (moodistGetApi), this is what separately built C++
// extensions check: they pass the version they were compiled against to get_core_api_ptr(version).
// The build magic can't serve them, since it only matches components from the same build.
constexpr uint32_t kMoodistApiVersion = 7;

// Build magic - changes per build to catch mismatched libraries
// This is generated by CMake (random value at configure time)
#ifndef MOODIST_BUILD_MAGIC
#define MOODIST_BUILD_MAGIC 0x0000000000000000ULL // Default for development
#endif

constexpr uint64_t kMoodistBuildMagic = MOODIST_BUILD_MAGIC;

} // namespace moodist
